use App\Repository\Workshop\WorkOrderRepository;
use App\Service\OfferCalculator;
use App\Service\Pdf\CompanyProfileProvider;
use App\Service\Settings\SettingsManager;
use App\Service\WorkOrderCalculator;
use App\Settings\SettingsRegistry;
use Symfony\Bundle\FrameworkBundle\Test\KernelTestCase;

/**
 * Renders the PDF Twig templates directly and verifies key pre-Dompdf HTML.
 *
 * Checking content at this layer is far more robust than scraping bytes out
 * of a compressed PDF stream. Each test resets the company profile so it is
 * insensitive to ordering with other tests that mutate settings.
 */
class PdfTemplateTest extends KernelTestCase
{
    private function resetCompanyProfile(string $name = 'PDF Test Workshop'): void
    {
        $manager = static::getContainer()->get(SettingsManager::class);

        $manager->setMany(SettingsRegistry::SECTION_COMPANY, [
            SettingsRegistry::KEY_COMPANY_NAME => $name,
            SettingsRegistry::KEY_COMPANY_ID => '000000',
            SettingsRegistry::KEY_VAT_NUMBER => 'VAT000000',
            SettingsRegistry::KEY_ADDRESS => 'Sample Street 1',
            SettingsRegistry::KEY_CITY => 'Testville',
            SettingsRegistry::KEY_COUNTRY => 'Testland',
            SettingsRegistry::KEY_PHONE => '+0 000 0000',
            SettingsRegistry::KEY_EMAIL => 'hello@pdftest.local',
            SettingsRegistry::KEY_WEBSITE => 'https://pdftest.local',
        ]);
        $manager->setFilePath(SettingsRegistry::SECTION_COMPANY, SettingsRegistry::KEY_LOGO_PATH, null);
    }

    public function testOfferPdfTemplateIncludesCompanyAndFooter(): void
    {
        self::bootKernel();
        $this->resetCompanyProfile('PDF Test Workshop');

        $container = static::getContainer();
        $twig = $container->get('twig');
        $offer = $container->get(OfferRepository::class)->findOneBy(['number' => 'OF-2026-0001']);
        self::assertNotNull($offer);
        $container->get(OfferCalculator::class)->recalculate($offer);
        $companyProvider = $container->get(CompanyProfileProvider::class);

        $html = $twig->render('pdf/offer.html.twig', [
            'offer' => $offer,
            'company' => $companyProvider->getCompany(),
            'logo_path' => $companyProvider->getLogoAbsolutePath(),
        ]);

        $this->assertStringContainsString('OF-2026-0001', $html);
        $this->assertStringContainsString('PDF Test Workshop', $html);
        $this->assertStringContainsString('Generated by Carstio', $html);
        $this->assertStringContainsString('Offer', $html);
    }

