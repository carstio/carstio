        ]);

        $this->assertPrintFriendlyTableStyles($html);
    }

    private function assertPrintFriendlyTableStyles(string $html): void
    {
        // Bootstrap's heavy dark-table helper must never reach a PDF.
        $this->assertStringNotContainsString('table-dark', $html);

        // The previous dark slate header background (#1f2937) and the
        // even-row zebra fill (#fafafa). Either coming back means somebody
        // brought the heavy headers back.
        $this->assertStringNotContainsString('background: #1f2937', $html);
        $this->assertStringNotContainsString('background:#1f2937', $html);
        $this->assertStringNotContainsString('nth-child(even)', $html);

        // Sanity-check the new style is actually the one being emitted.
        $this->assertStringContainsString('background: #ffffff', $html);
    }
}
