            'logo_path' => null,
        ]);

        $this->assertStringNotContainsString('<img src="', $html);
        $this->assertStringContainsString('PDF Test Workshop', $html);
    }

    public function testOfferPdfDoesNotExposeCostOrParentMargin(): void
    {
        self::bootKernel();
        $this->resetCompanyProfile('PDF Test Workshop');

        $container = static::getContainer();
        $twig = $container->get('twig');
        $offer = $container->get(OfferRepository::class)->findOneBy(['number' => 'OF-2026-0001']);
