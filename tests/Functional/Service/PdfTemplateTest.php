            'offer' => $offer,
            'company' => $companyProvider->getCompany(),
            'logo_path' => $companyProvider->getLogoAbsolutePath(),
        ]);

        // Translated parts-margin labels must never reach a client-facing PDF.
        $this->assertStringNotContainsString('Parts margin', $html);
        $this->assertStringNotContainsString('Parts cost', $html);
        $this->assertStringNotContainsString('Parts profit', $html);
        $this->assertStringNotContainsString('Internal use only', $html);
    }

