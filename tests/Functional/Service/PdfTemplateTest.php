    /**
     * Guards against regressing to the dark table headers / dark zebra
     * backgrounds the PDFs used to ship with. Those waste printer ink and
     * make the document look heavy. The current style keeps headers on a
     * white background with a thin border.
     */
    public function testOfferPdfUsesPrintFriendlyTableStyles(): void
    {
        self::bootKernel();
        $this->resetCompanyProfile('PDF Test Workshop');

        $container = static::getContainer();
        $twig = $container->get('twig');
        $offer = $container->get(OfferRepository::class)->findOneBy(['number' => 'OF-2026-0001']);
        self::assertNotNull($offer);
        $container->get(OfferCalculator::class)->recalculate($offer);
        $companyProvider = $container->get(CompanyProfileProvider::class);

        $html = $twig->render('pdf/offer.html.twig', [
            'offer' => $offer,
            'company' => $companyProvider->getCompany(),
            'logo_path' => $companyProvider->getLogoAbsolutePath(),
        ]);

        $this->assertPrintFriendlyTableStyles($html);
    }

    public function testWorkOrderPdfUsesPrintFriendlyTableStyles(): void
    {
        self::bootKernel();
        $this->resetCompanyProfile('PDF Test Workshop');

        $container = static::getContainer();
        $twig = $container->get('twig');
        $workOrder = $container->get(WorkOrderRepository::class)->findOneBy(['number' => 'WO-2026-0001']);
